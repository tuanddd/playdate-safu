// Merge each row's runs of '#' into rects — fewest shapes, exact pixels.
function pixPath(name) {
  const g = PIX[name];
  if (!g) throw new Error('no pixel icon: ' + name);
  const out = [];
  g.forEach((row, y) => {
    if (row.length !== 14) throw new Error(`${name} row ${y} is ${row.length} wide, need 14`);
    let x = 0;
    while (x < 14) {
      if (row[x] === '#') {
        let run = 0;
        while (x + run < 14 && row[x + run] === '#') run++;
        out.push(`M${x},${y}h${run}v1h-${run}z`);
        x += run;
      } else x++;
    }
  });
  return out.join('');
}

